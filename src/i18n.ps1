function Resolve-Lang([string]$pref) {
    if ($pref -in 'zh', 'en') { return $pref }
    if ((Get-UICulture).Name -like 'zh*') { 'zh' } else { 'en' }
}

if (-not $script:Lang) { $script:Lang = Resolve-Lang 'auto' }

function Tr([string]$key) {
    $s = $script:Strings[$script:Lang][$key]
    if ($null -eq $s) { $s = $script:Strings['en'][$key] }
    if ($null -eq $s) { return $key }
    if ($args.Count) { return ($s -f $args) }
    $s
}

# Status / connection codes -> localized text
function Format-Status([string]$code) { if ($code) { Tr "st_$code" } else { '' } }
function Format-Connection([string]$code) { if ($code) { Tr "conn_$code" } else { '' } }
